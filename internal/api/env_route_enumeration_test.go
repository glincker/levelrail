var envRoutePath = regexp.MustCompile(`/env(/|$|-)|/secrets(/|$)|vault-env|preview-env|branch-env|/previews/\{number\}/env`)

func TestEveryEnvOrSecretRouteIsAccountedFor(t *testing.T) {
	files, err := filepath.Glob("routes*.go")
	if err != nil || len(files) == 0 {
		t.Fatalf("no route files: %v", err)
	}
	var unknown []string
	seen := 0
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") {
			continue
		}
		raw, err := os.ReadFile(filepath.Clean(f))
		if err != nil {
			t.Fatal(err)
		}
		for _, m := range envRouteLine.FindAllStringSubmatch(string(raw), -1) {
			if !envRoutePath.MatchString(m[2]) && !strings.HasSuffix(m[2], "/clone") {
				continue
			}
			seen++
			if _, ok := envRouteCoverage[m[3]]; !ok {
				unknown = append(unknown, m[1]+" "+m[2]+" "+m[3])
			}
		}
	}
	if seen < 10 {
		t.Fatalf("only %d env or secret routes found, the parser is broken", seen)
	}
	sort.Strings(unknown)
	for _, u := range unknown {
		t.Errorf("route not in envRouteCoverage (add it with a reason, validated or exempt): %s", u)
	}
}
