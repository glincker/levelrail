package fielddesc

import (
	"fmt"
	"strings"
)

// FlagSpec is one CLI flag derived from the descriptors.
type FlagSpec struct {
	Name  string
	Key   string
	Usage string
	File  bool
	Bool  bool
}

// FlagSpecs lists each distinct flag once, in field order. Variants that share a wire
// key share one flag, so the first descriptor carrying the flag supplies its help.
func (r Resource) FlagSpecs() []FlagSpec {
	return r.flagSpecs(nil)
}

// FlagSpecsWhen is FlagSpecs limited to the fields visible for values, so a per provider
// verb registers only that provider's flags.
func (r Resource) FlagSpecsWhen(values map[string]string) []FlagSpec {
	return r.flagSpecs(values)
}

func (r Resource) flagSpecs(values map[string]string) []FlagSpec {
	seen := map[string]bool{}
	var out []FlagSpec
	for _, f := range r.Fields {
		if f.Flag == "" || seen[f.Flag] || (values != nil && !f.Visible(values)) {
			continue
		}
		seen[f.Flag] = true
		out = append(out, FlagSpec{Name: f.Flag, Key: f.Key, Usage: f.Doc, File: f.FlagFile, Bool: f.Type == TypeBool})
	}
	return out
}

// Markdown renders the docs table for a resource.
func (r Resource) Markdown() string {
	var b strings.Builder
	b.WriteString("| Field | Type | Required | Shown when | CLI flag | Description |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- |\n")
	for _, f := range r.Fields {
		flag := "none"
		if f.Flag != "" {
			flag = "`--" + f.Flag + "`"
		}
		req := "no"
		if f.Required {
			req = "yes"
		}
		typ := string(f.Type)
		if f.Secret {
			typ += ", write only"
		}
		fmt.Fprintf(&b, "| `%s` (%s) | %s | %s | %s | %s | %s |\n", f.Key, f.ID, typ, req, whenText(f.ShowWhen), flag, f.Doc)
	}
	return b.String()
}

func whenText(cs []Condition) string {
	if len(cs) == 0 {
		return "always"
	}
	parts := make([]string, 0, len(cs))
	for _, c := range cs {
		parts = append(parts, fmt.Sprintf("`%s` is %s", c.Field, strings.Join(c.Equals, " or ")))
	}
	return strings.Join(parts, " and ")
}

// DocsPage renders the whole generated docs file of a resource.
func DocsPage(r Resource) string {
	slug := strings.TrimSuffix(r.Docs.File, ".md")
	return "---\ntitle: \"" + r.Docs.Title + "\"\ndescription: " + r.Docs.Description + "\n\"og:url\": \"https://docs.levelrail.com/" + slug + "\"\n---\n\n" +
		"{/* Generated by scripts/gen-field-docs from internal/fielddesc. Do not edit by hand. */}\n\n" +
		"The dashboard form, the CLI flags and the API all read one field registry, served at `GET /api/v1/field-descriptors/" + r.Name + "`. Secrets are write only: they are accepted on create and update and never returned.\n\n" +
		r.Markdown()
}
