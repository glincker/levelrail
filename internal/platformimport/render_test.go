func renderDiscover(t *testing.T, fake *fakerender.Server) *Discovery {
	t.Helper()
	srv := httptest.NewServer(fake.Handler())
	t.Cleanup(srv.Close)
	src, err := NewRender(srv.URL, fakerender.Token, testOpts)
	if err != nil {
		t.Fatal(err)
	}
	d, err := src.Discover(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	if v := fake.Violations(); len(v) != 0 {
		t.Fatalf("source was written to: %v", v)
	}
	return d
}

func TestRenderDiscover(t *testing.T) {
	d := renderDiscover(t, fakerender.New())
	// Four services over two pages: the cron job becomes a warning, not an app.
	if len(d.Apps) != 3 || d.Apps[0].Name != "api" || d.Apps[1].Name != "mailer" || d.Apps[2].Name != "site" {
		t.Fatalf("apps: %+v", d.Apps)
	}
	web := d.Apps[0]
	if web.Kind != SourceGit || web.GitURL != "https://github.com/acme/api" || web.GitBranch != "main" || web.BuildPath != "server" ||
		web.BuildPack != "node" || web.Replicas != 2 || web.Server != "oregon" {
		t.Errorf("web: %+v", web)
	}
	if web.Health == nil || web.Health.Path != "/healthz" {
		t.Errorf("health: %+v", web.Health)
	}
	if len(web.Volumes) != 1 || web.Volumes[0].ContainerPath != "/var/data" || web.Volumes[0].SizeBytes != 10<<30 {
		t.Errorf("volumes: %+v", web.Volumes)
	}
	worker := d.Apps[1]
	if worker.Kind != SourceImage || worker.Image != "ghcr.io/acme/mailer:1.2" || len(worker.Notes) == 0 || !strings.Contains(worker.Notes[0].Reason, "background worker") {
		t.Errorf("worker: %+v", worker)
	}
	site := d.Apps[2]
	if site.Kind != SourceGit || site.BuildMethod != "static" || site.GitBranch != "trunk" {
		t.Errorf("site: %+v", site)
	}
	all := strings.Join(d.Warnings, "\n")
	for _, want := range []string{`cron job nightly runs "node jobs/nightly.js" on schedule "0 3 * * *"`, "Render Postgres main-db", "Render Key Value cache"} {
		if !strings.Contains(all, want) {
			t.Errorf("warnings miss %q:\n%s", want, all)
		}
	}
	if len(d.Databases) != 2 {
		t.Fatalf("databases: %+v", d.Databases)
	}
	if pg := d.Databases[0]; pg.Engine != "postgres" || pg.Version != "16" || pg.Name != "main-db" {
		t.Errorf("pg: %+v", pg)
	}
	if kv := d.Databases[1]; kv.Engine != "redis" || kv.Name != "cache" {
		t.Errorf("kv: %+v", kv)
	}
}

func TestRenderEnvAndGeneratedVars(t *testing.T) {
	d := renderDiscover(t, fakerender.New())
	web := d.Apps[0]
	if e := envOf(web, "NODE_ENV"); e.Secret || e.Value != "production" {
		t.Errorf("NODE_ENV: %+v", e)
	}
	if e := envOf(web, "SESSION_SECRET"); !e.Secret || e.Value != fakerender.SecretVal {
		t.Errorf("SESSION_SECRET: %+v", e)
	}
	if e := envOf(web, "JWT_SALT"); !e.Secret || e.Value != "" {
		t.Errorf("generated var should be a secret without a value: %+v", e)
	}
	all := strings.Join(d.Warnings, "\n")
	if !strings.Contains(all, "generated by Render and not readable, set it manually: JWT_SALT") || strings.Contains(all, fakerender.SecretVal) {
		t.Errorf("warnings: %s", all)
	}
}

