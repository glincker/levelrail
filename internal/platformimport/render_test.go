func TestRenderUnauthorizedRedactsToken(t *testing.T) {
	srv := httptest.NewServer(fakerender.New().Handler())
	defer srv.Close()
	src, _ := NewRender(srv.URL, "wrong-token-fixture", testOpts)
	_, err := src.Discover(context.Background())
	var api *APIError
	if err == nil || !errors.As(err, &api) || api.Status != 401 || strings.Contains(err.Error(), "wrong-token-fixture") {
		t.Fatalf("want redacted 401, got %v", err)
	}
}

func TestRenderPlatformWiring(t *testing.T) {
	if p, err := ParsePlatform("render"); err != nil || p != Render {
		t.Fatalf("ParsePlatform: %v %v", p, err)
	}
	if _, err := NewSource(Render, "", "tok", testOpts); err != nil {
		t.Errorf("empty url should use the public API: %v", err)
	}
	if _, err := ParsePlatform("nope"); err == nil || !strings.Contains(err.Error(), "render") {
		t.Errorf("error text: %v", err)
	}
}
