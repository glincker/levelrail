package walship

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Sink is where the replica lives (a directory here; an object store later).
type Sink interface {
	Put(name string, r io.Reader) error
	Get(name string) (io.ReadCloser, error)
	List(prefix string) ([]string, error)
}

// DirSink stores replica objects as files under Dir.
type DirSink struct{ Dir string }

// Put writes name atomically.
func (d DirSink) Put(name string, r io.Reader) error {
	p := filepath.Join(d.Dir, name)
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		return fmt.Errorf("walship: mkdir: %w", err)
	}
	tmp, err := os.CreateTemp(filepath.Dir(p), ".put-*")
	if err != nil {
		return fmt.Errorf("walship: temp: %w", err)
	}
	if _, err := io.Copy(tmp, r); err != nil {
		_ = tmp.Close()
		_ = os.Remove(tmp.Name())
		return fmt.Errorf("walship: write: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("walship: close: %w", err)
	}
	return os.Rename(tmp.Name(), p)
}

// Get opens name.
func (d DirSink) Get(name string) (io.ReadCloser, error) {
	return os.Open(filepath.Join(d.Dir, name)) //nolint:gosec // names are generated by this package
}

// List returns object names with the prefix, sorted.
func (d DirSink) List(prefix string) ([]string, error) {
	var out []string
	err := filepath.WalkDir(d.Dir, func(p string, e os.DirEntry, err error) error {
		if err != nil {
			if os.IsNotExist(err) {
				return nil
			}
			return err
		}
		if e.IsDir() || strings.HasPrefix(e.Name(), ".put-") {
			return nil
		}
		rel, _ := filepath.Rel(d.Dir, p)
		rel = filepath.ToSlash(rel)
		if strings.HasPrefix(rel, prefix) {
			out = append(out, rel)
		}
		return nil
	})
	sort.Strings(out)
	return out, err
}

type countReader struct {
	r io.Reader
	n int64
}

func (c *countReader) Read(p []byte) (int, error) {
	n, err := c.r.Read(p)
	c.n += int64(n)
	return n, err
}

func snapshotName(gen int) string { return fmt.Sprintf("gen-%06d/snapshot.db.gz", gen) }

func headerName(gen int, seq uint32) string {
	return fmt.Sprintf("gen-%06d/e%010d.hdr", gen, seq)
}

func segmentName(gen int, seq uint32, off int64) string {
	return fmt.Sprintf("gen-%06d/e%010d-%014d.seg.gz", gen, seq, off)
}
