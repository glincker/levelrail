const (
	catalogPath = "docs/integrations/catalog.json"
	docsJSON    = "docs/docs.json"
	llmsPath    = "docs/public/llms.txt"
	docsBase    = "https://docs.levelrail.com/"
	llmsBegin   = "<!-- integrations:begin -->"
	llmsEnd     = "<!-- integrations:end -->"
	tabTitle    = "Integrations"
	maxTitle    = 65
	maxDesc     = 160
)

type permission struct {
	What   string `json:"what"`
	Detail string `json:"detail"`
}

type problem struct {
	Problem string `json:"problem"`
	Fix     string `json:"fix"`
}

type qa struct {
	Q string `json:"q"`
	A string `json:"a"`
}

type entry struct {
	ID          string       `json:"id"`
	Vendor      string       `json:"vendor"`
	Category    string       `json:"category"`
	What        string       `json:"what"`
	TitleWhat   string       `json:"title_what"`
	Summary     string       `json:"summary"`
	Gets        []string     `json:"gets"`
	UIPath      string       `json:"ui_path"`
	CLI         []string     `json:"cli"`
	Auth        []string     `json:"auth"`
	Permissions []permission `json:"permissions"`
	Endpoint    string       `json:"endpoint"`
	Limits      []string     `json:"limits"`
	DocsURL     string       `json:"docs_url"`
	Trouble     []problem    `json:"trouble"`
	FAQ         []qa         `json:"faq"`
	Related     []string     `json:"related"`
}

type category struct {
	ID    string `json:"id"`
	Title string `json:"title"`
	Blurb string `json:"blurb"`
}

type catalog struct {
	Version    int        `json:"version"`
	Categories []category `json:"categories"`
	Entries    []entry    `json:"entries"`
}

