// Command gen-integration-docs renders docs/integrations/catalog.json into
// per-vendor pages, category indexes, the docs.json Integrations tab and the
// llms.txt Integrations section.
//
// Usage (from the repo root): go run ./scripts/gen-integration-docs [-check]
package main

