var (
	codeSplit = regexp.MustCompile("`")
	riskyTok  = regexp.MustCompile(`[^\s(]*[<{][^\s<>{}]*[>}][^\s)]*`)
	trailPunc = regexp.MustCompile(`[.,;:]+$`)
)

// safe wraps tokens holding <...> or {...} outside code spans in backticks
// so MDX does not parse them as JSX or expressions.
func safe(s string) string {
	parts := codeSplit.Split(s, -1)
	for i := 0; i < len(parts); i += 2 {
		parts[i] = riskyTok.ReplaceAllStringFunc(parts[i], func(m string) string {
			tail := trailPunc.FindString(m)
			return "`" + strings.TrimSuffix(m, tail) + "`" + tail
		})
	}
	return strings.Join(parts, "`")
}

var uiPathRe = regexp.MustCompile(`^(.*?) \((/[^)]*)\)(?:, then (.*))?$`)

// uiStep turns "Nav > Page (/route), then action" into a sentence with the
// route as code; a path with no route is kept as the bold nav path.
func uiStep(p string) string {
	m := uiPathRe.FindStringSubmatch(p)
	if m == nil {
		return fmt.Sprintf("In the dashboard, open **%s**.", safe(p))
	}
	s := fmt.Sprintf("In the dashboard, open **%s** (`%s`)", safe(m[1]), m[2])
	if m[3] != "" {
		s += ", then " + safe(m[3])
	}
	return s + "."
}

func cell(s string) string { return strings.ReplaceAll(safe(s), "|", `\|`) }

func yamlQuote(s string) string {
	return `"` + strings.ReplaceAll(strings.ReplaceAll(s, `\`, `\\`), `"`, `\"`) + `"`
}

func title(e entry) string {
	w := e.TitleWhat
	if w == "" {
		w = meta[e.Category].titleWhat
	}
	return fmt.Sprintf("Use %s with Levelrail: %s", e.Vendor, w)
}

func pagePath(e entry) string { return "integrations/" + e.Category + "/" + e.ID }

func renderEntry(e entry, byKey map[string]entry, cats map[string]category) string {
	var b strings.Builder
	m := meta[e.Category]
	fmt.Fprintf(&b, "---\ntitle: %s\nsidebarTitle: %s\ndescription: %s\n---\n\n", yamlQuote(title(e)), yamlQuote(e.Vendor), yamlQuote(e.Summary))
	fmt.Fprintf(&b, "%s\n\nThis page covers how to %s.\n\n", safe(e.Summary), safe(e.What))

	b.WriteString("## What you get\n\n")
	for _, g := range e.Gets {
		fmt.Fprintf(&b, "- %s\n", safe(g))
	}

	b.WriteString("\n## Set up\n\n")
	n := 1
	for _, a := range e.Auth {
		fmt.Fprintf(&b, "%d. Prepare the credential. %s\n", n, safe(a))
		n++
	}
	fmt.Fprintf(&b, "%d. %s\n", n, uiStep(e.UIPath))
	n++
	fmt.Fprintf(&b, "%d. %s\n\n", n, safe(m.verify))

	b.WriteString("From the CLI:\n\n```bash\n")
	for _, c := range e.CLI {
		b.WriteString(c + "\n")
	}
	b.WriteString("```\n\n")

	b.WriteString("## Permissions and scopes\n\n| Needed | Why |\n| --- | --- |\n")
	for _, p := range e.Permissions {
		fmt.Fprintf(&b, "| %s | %s |\n", cell(p.What), cell(p.Detail))
	}

	b.WriteString("\n## Endpoint and format\n\n" + safe(e.Endpoint) + "\n\n")

	b.WriteString("## Security notes\n\n")
	for _, s := range m.security {
		fmt.Fprintf(&b, "- %s\n", s)
	}
	b.WriteString("- Nothing you enter here is shown again after you save it.\n\n")

	b.WriteString("## Limits and caveats\n\n")
	for _, l := range e.Limits {
		fmt.Fprintf(&b, "- %s\n", safe(l))
	}

	b.WriteString("\n## Troubleshooting\n\n")
	for _, t := range e.Trouble {
		fmt.Fprintf(&b, "**%s.** %s\n\n", strings.TrimRight(safe(t.Problem), "."), safe(t.Fix))
	}

	b.WriteString("## FAQ\n\n")
	for _, f := range e.FAQ {
		fmt.Fprintf(&b, "**%s**\n\n%s\n\n", safe(f.Q), safe(f.A))
	}

	b.WriteString("## Related\n\n")
	for _, r := range e.Related {
		t := byKey[r]
		fmt.Fprintf(&b, "- [%s](/integrations/%s): %s\n", t.Vendor, r, cats[t.Category].Title)
	}
	fmt.Fprintf(&b, "- [All %s](/integrations/%s)\n", strings.ToLower(cats[e.Category].Title), e.Category)
	if e.DocsURL != "" {
		fmt.Fprintf(&b, "- [%s documentation](%s), maintained by the vendor\n", e.Vendor, e.DocsURL)
	}
	return b.String()
}

func renderCategory(c category, es []entry) string {
	var b strings.Builder
	d := fmt.Sprintf("%s that Levelrail supports: %s", c.Title, c.Blurb)
	fmt.Fprintf(&b, "---\ntitle: %s\nsidebarTitle: %s\ndescription: %s\n---\n\n", yamlQuote(c.Title+" with Levelrail"), yamlQuote(c.Title), yamlQuote(d))
	fmt.Fprintf(&b, "%s\n\n| Integration | What it enables |\n| --- | --- |\n", c.Blurb)
	for _, e := range es {
		fmt.Fprintf(&b, "| [%s](/%s) | %s |\n", cell(e.Vendor), pagePath(e), cell(upperFirst(e.What)))
	}
	b.WriteString("\n[Back to all integrations](/integrations/)\n")
	return b.String()
}

func upperFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func renderIndex(cs []category, by map[string][]entry) string {
	var b strings.Builder
	b.WriteString("---\ntitle: \"Levelrail integrations: backups, registries, providers and sign-in\"\nsidebarTitle: \"Overview\"\ndescription: \"Every backup destination, registry, cloud provider, sign-in method, database engine, notification channel and git host Levelrail supports, with exact setup steps.\"\n---\n\n")
	b.WriteString("Each page below describes one integration: the dashboard path, the CLI command, the permissions it needs and how it fails. Everything listed is implemented today; planned work is called out on the page that would own it.\n\n")
	for _, c := range cs {
		fmt.Fprintf(&b, "## [%s](/integrations/%s)\n\n%s\n\n", c.Title, c.ID, c.Blurb)
		var names []string
		for _, e := range by[c.ID] {
			names = append(names, fmt.Sprintf("[%s](/%s)", e.Vendor, pagePath(e)))
		}
		b.WriteString(strings.Join(names, ", ") + "\n\n")
	}
	return b.String()
}

func leaves(root string) (map[string]bool, error) {
	out := map[string]bool{}
	base := filepath.Join(root, "docs", "integrations")
	err := filepath.Walk(base, func(p string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if !info.IsDir() && strings.HasSuffix(p, ".md") {
			rel, _ := filepath.Rel(root, p)
			out[filepath.ToSlash(rel)] = true
		}
		return nil
	})
	return out, err
}

func tabBlock(cs []category, by map[string][]entry) string {
	var b strings.Builder
	b.WriteString("      {\n        \"tab\": \"" + tabTitle + "\",\n        \"groups\": [\n")
	b.WriteString("          {\n            \"group\": \"Overview\",\n            \"pages\": [\n              \"integrations/index\"\n            ]\n          }")
	for _, c := range cs {
		b.WriteString(",\n          {\n            \"group\": " + jsonString(c.Title) + ",\n            \"pages\": [\n")
		pages := []string{"integrations/" + c.ID + "/index"}
		for _, e := range by[c.ID] {
			pages = append(pages, pagePath(e))
		}
		for i, p := range pages {
			b.WriteString("              " + jsonString(p))
			if i < len(pages)-1 {
				b.WriteString(",")
			}
			b.WriteString("\n")
		}
		b.WriteString("            ]\n          }")
	}
	b.WriteString("\n        ],\n        \"icon\": \"/assets/icons/tree-structure.svg\"\n      }")
	return b.String()
}

func jsonString(s string) string {
	raw, _ := json.Marshal(s)
	return string(raw)
}

// patchDocsJSON replaces the Integrations tab object, or inserts it before
// the Concepts tab, leaving every other byte of docs.json untouched.
func patchDocsJSON(src string, block string) (string, error) {
	lines := strings.Split(src, "\n")
	start := -1
	for i, l := range lines {
		if l == "        \"tab\": \""+tabTitle+"\"," && i > 0 && lines[i-1] == "      {" {
			start = i - 1
			break
		}
	}
	if start >= 0 {
		end := -1
		for i := start + 1; i < len(lines); i++ {
			if lines[i] == "      }," || lines[i] == "      }" {
				end = i
				break
			}
		}
		if end < 0 {
			return "", fmt.Errorf("docs.json: unterminated Integrations tab")
		}
		term := strings.TrimPrefix(lines[end], "      }")
		out := append([]string{}, lines[:start]...)
		out = append(out, strings.Split(block+term, "\n")...)
		out = append(out, lines[end+1:]...)
		return strings.Join(out, "\n"), nil
	}
	for i, l := range lines {
		if l == "        \"tab\": \"Concepts\"," && i > 0 && lines[i-1] == "      {" {
			out := append([]string{}, lines[:i-1]...)
			out = append(out, strings.Split(block+",", "\n")...)
			out = append(out, lines[i-1:]...)
			return strings.Join(out, "\n"), nil
		}
	}
	return "", fmt.Errorf("docs.json: Concepts tab not found, cannot place Integrations tab")
}

func llmsSection(cs []category, by map[string][]entry) string {
	var b strings.Builder
	b.WriteString(llmsBegin + "\n## Integrations\n\n")
	fmt.Fprintf(&b, "- [Integrations overview](%sintegrations/index): every backup destination, registry, provider, sign-in method, database engine, notification channel and git host, with setup steps.\n", docsBase)
	for _, c := range cs {
		fmt.Fprintf(&b, "\n### %s\n\n", c.Title)
		for _, e := range by[c.ID] {
			fmt.Fprintf(&b, "- [%s](%s%s): %s.\n", e.Vendor, docsBase, pagePath(e), e.What)
		}
	}
	b.WriteString("\n" + llmsEnd + "\n")
	return b.String()
}

func patchLLMs(src, section string) (string, error) {
	if s := strings.Index(src, llmsBegin); s >= 0 {
		e := strings.Index(src, llmsEnd)
		if e < s {
			return "", fmt.Errorf("llms.txt: end marker missing")
		}
		return src[:s] + section + strings.TrimPrefix(src[e+len(llmsEnd):], "\n"), nil
	}
	i := strings.Index(src, "\n## Optional")
	if i < 0 {
		return "", fmt.Errorf("llms.txt: no Optional section to insert before")
	}
	return src[:i+1] + section + src[i:], nil
}

func build(root string) (map[string]string, error) {
	raw, err := os.ReadFile(filepath.Join(root, catalogPath)) //nolint:gosec // developer tool
	if err != nil {
		return nil, err
	}
	var cat catalog
	if err := json.Unmarshal(raw, &cat); err != nil {
		return nil, fmt.Errorf("%s: %w", catalogPath, err)
	}
	cats := map[string]category{}
	for _, c := range cat.Categories {
		cats[c.ID] = c
	}
	byKey := map[string]entry{}
	by := map[string][]entry{}
	for _, e := range cat.Entries {
		if _, ok := cats[e.Category]; !ok {
			return nil, fmt.Errorf("entry %s: unknown category %q", e.ID, e.Category)
		}
		if len(e.Trouble) < 3 || len(e.Gets) == 0 || e.UIPath == "" || len(e.CLI) == 0 || e.DocsURL == "" {
			return nil, fmt.Errorf("entry %s/%s: incomplete (need gets, ui_path, cli, docs_url, 3 trouble items)", e.Category, e.ID)
		}
		key := e.Category + "/" + e.ID
		if _, dup := byKey[key]; dup {
			return nil, fmt.Errorf("duplicate entry %s", key)
		}
		byKey[key] = e
		by[e.Category] = append(by[e.Category], e)
	}
	for k, e := range byKey {
		for _, r := range e.Related {
			if _, ok := byKey[r]; !ok {
				return nil, fmt.Errorf("entry %s: related %q does not exist", k, r)
			}
		}
		if n := len(title(e)); n > maxTitle {
			fmt.Fprintf(os.Stderr, "note: title over %d chars (%d): %s\n", maxTitle, n, title(e))
		}
		if n := len(e.Summary); n > maxDesc {
			return nil, fmt.Errorf("entry %s: summary is %d chars, limit %d", k, n, maxDesc)
		}
	}

	out := map[string]string{"docs/integrations/index.md": renderIndex(cat.Categories, by)}
	for _, c := range cat.Categories {
		out["docs/integrations/"+c.ID+"/index.md"] = renderCategory(c, by[c.ID])
		for _, e := range by[c.ID] {
			out["docs/"+pagePath(e)+".md"] = renderEntry(e, byKey, cats)
		}
	}

	dj, err := os.ReadFile(filepath.Join(root, docsJSON)) //nolint:gosec // developer tool
	if err != nil {
		return nil, err
	}
	patched, err := patchDocsJSON(string(dj), tabBlock(cat.Categories, by))
	if err != nil {
		return nil, err
	}
	var probe map[string]any
	if err := json.Unmarshal([]byte(patched), &probe); err != nil {
		return nil, fmt.Errorf("docs.json would be invalid: %w", err)
	}
	out[docsJSON] = patched

	ll, err := os.ReadFile(filepath.Join(root, llmsPath)) //nolint:gosec // developer tool
	if err != nil {
		return nil, err
	}
	lp, err := patchLLMs(string(ll), llmsSection(cat.Categories, by))
	if err != nil {
		return nil, err
	}
	out[llmsPath] = lp

	for p, body := range out {
		if strings.ContainsAny(body, string([]rune{0x2014, 0x2013})) {
			return nil, fmt.Errorf("%s contains an em or en dash", p)
		}
	}
	return out, nil
}

func main() {
	check := flag.Bool("check", false, "fail if generated files are stale instead of writing them")
	root := flag.String("root", ".", "repository root")
	flag.Parse()

	out, err := build(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	existing, err := leaves(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var stale []string
	for p := range existing {
		if _, ok := out[p]; !ok {
			stale = append(stale, p+" (no longer generated)")
		}
	}
	for p, body := range out {
		cur, err := os.ReadFile(filepath.Join(*root, p)) //nolint:gosec // developer tool
		if err != nil || string(cur) != body {
			stale = append(stale, p)
		}
	}
	sort.Strings(stale)
	if len(stale) == 0 {
		fmt.Printf("integration docs up to date (%d files)\n", len(out))
		return
	}
	if *check {
		fmt.Fprintf(os.Stderr, "integration docs are stale: run go run ./scripts/gen-integration-docs\n  %s\n", strings.Join(stale, "\n  "))
		os.Exit(1)
	}
	for _, p := range stale {
		if strings.HasSuffix(p, "(no longer generated)") {
			_ = os.Remove(filepath.Join(*root, strings.TrimSuffix(p, " (no longer generated)")))
		}
	}
	for p, body := range out {
		full := filepath.Join(*root, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		if err := os.WriteFile(full, []byte(body), 0o644); err != nil { //nolint:gosec // docs files
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	fmt.Printf("integration docs updated (%d files)\n", len(out))
}
