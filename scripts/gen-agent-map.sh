#!/usr/bin/env bash
# Writes docs-local/agent-map.md: one line per Go package and web route, so agents skip exploratory greps.
# Usage: scripts/gen-agent-map.sh
set -euo pipefail

root="$(git rev-parse --show-toplevel)"
cd "$root"

out="docs-local/agent-map.md"
tmp="$(mktemp "$(git rev-parse --git-dir)/agent-map.XXXXXX")"
trap 'rm -f "$tmp"' EXIT

{
	echo "# Agent map (generated by scripts/gen-agent-map.sh, do not edit)"
	echo
	echo "## Go packages: path, first doc sentence"
	# %q keeps each package's doc on one line so the read loop stays simple.
	go list -e -f '{{.ImportPath}}{{"\t"}}{{printf "%q" .Doc}}' ./... 2>/dev/null |
		awk -F'\t' -v mod="$(head -n1 go.mod | awk '{print $2}')" '
		{
			path = $1; sub("^" mod "/?", "", path); if (path == "") path = "."
			doc = $2; gsub(/^"|"$/, "", doc); gsub(/\\n/, " ", doc)
			sub(/^Package [A-Za-z0-9_]+ /, "", doc)
			sub(/\. .*/, ".", doc)
			if (length(doc) > 100) doc = substr(doc, 1, 97) "..."
			print "- `" path "`" (doc == "" ? "" : ": " doc)
		}'
	echo
	echo "## Web routes: TanStack route path, file"
	find web/src/routes -name '*.tsx' ! -name '*.test.*' | sort | while IFS= read -r f; do
		# Files without a route (layouts, helpers) have no match; grep's exit 1 must not abort.
		r="$(grep -o "createFileRoute('[^']*')" "$f" | head -n1 | sed "s/createFileRoute('//; s/')//" || true)"
		[ -n "$r" ] && echo "- \`$r\` $f"
	done
} >"$tmp"

lines="$(wc -l <"$tmp" | tr -d ' ')"
if [ "$lines" -gt 200 ]; then
	echo "warning: agent map is $lines lines (one line per package and route)" >&2
fi

mkdir -p docs-local
mv "$tmp" "$out"
trap - EXIT
echo "wrote $out ($lines lines)"
