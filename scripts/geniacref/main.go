// Command geniacref writes docs/iac/reference.md from the published IaC JSON
// Schema, so the field reference cannot drift from the parser.
//
// Usage (repo root): go run ./scripts/geniacref [-check]
// With -check it exits non-zero when the committed page differs.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/GLINCKER/levelrail/internal/iac"
)

const pagePath = "docs/iac/reference.md"

type node = map[string]any

func main() {
	check := flag.Bool("check", false, "fail if the committed page differs")
	flag.Parse()
	raw, err := iac.SchemaJSON()
	if err != nil {
		fatal(err)
	}
	page, err := render(raw)
	if err != nil {
		fatal(err)
	}
	if *check {
		cur, err := os.ReadFile(pagePath)
		if err != nil || !bytes.Equal(cur, page) {
			fmt.Fprintln(os.Stderr, pagePath+" is stale, run: go run ./scripts/geniacref")
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(pagePath, page, 0o600); err != nil {
		fatal(err)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "geniacref:", err)
	os.Exit(1)
}

// render builds the page: one section per kind, in the order the schema lists them.
func render(raw []byte) ([]byte, error) {
	var root node
	if err := json.Unmarshal(raw, &root); err != nil {
		return nil, err
	}
	kinds := kindSpecs(root)
	var b strings.Builder
	b.WriteString("---\ntitle: \"IaC reference\"\ndescription: Every resource kind, its fields, types and which are required. Generated from the JSON Schema.\n---\n\n")
	b.WriteString("<!-- Generated by scripts/geniacref from the IaC JSON Schema. Do not edit. -->\n\n")
	b.WriteString("Every document has `version: 1`, a `kind`, a `metadata.name` and a `spec`. Fields marked required must be set.\n")
	for _, k := range kinds {
		fmt.Fprintf(&b, "\n## %s\n\n", k.kind)
		spec := resolve(root, k.spec)
		writeFields(&b, root, spec, "spec")
		if k.kind == "App" {
			props, _ := spec["properties"].(node)
			if svc, ok := props["service"].(node); ok {
				b.WriteString("\n`spec.service` fields:\n\n")
				writeFields(&b, root, resolve(root, svc), "spec.service")
			}
		}
	}
	return []byte(b.String()), nil
}

type kindSpec struct {
	kind string
	spec node
}

func kindSpecs(root node) []kindSpec {
	var out []kindSpec
	all, _ := root["allOf"].([]any)
	for _, a := range all {
		m, _ := a.(node)
		cond, _ := m["if"].(node)
		cp, _ := cond["properties"].(node)
		kc, _ := cp["kind"].(node)
		kind, _ := kc["const"].(string)
		then, _ := m["then"].(node)
		tp, _ := then["properties"].(node)
		spec, _ := tp["spec"].(node)
		if kind != "" && spec != nil {
			out = append(out, kindSpec{kind, spec})
		}
	}
	return out
}

// resolve follows a local $ref chain, keeping the referring node's description.
func resolve(root, n node) node {
	for i := 0; i < 8; i++ {
		ref, ok := n["$ref"].(string)
		if !ok || !strings.HasPrefix(ref, "#/") {
			return n
		}
		var cur any = root
		for _, part := range strings.Split(ref[2:], "/") {
			m, _ := cur.(node)
			cur = m[part]
		}
		t, _ := cur.(node)
		merged := node{}
		for k, v := range t {
			merged[k] = v
		}
		for k, v := range n {
			if k != "$ref" {
				merged[k] = v
			}
		}
		n = merged
	}
	return n
}

func writeFields(b *strings.Builder, root, spec node, prefix string) {
	props, _ := spec["properties"].(node)
	if len(props) == 0 {
		b.WriteString("No fields.\n")
		return
	}
	req := map[string]bool{}
	if r, ok := spec["required"].([]any); ok {
		for _, x := range r {
			if s, ok := x.(string); ok {
				req[s] = true
			}
		}
	}
	names := make([]string, 0, len(props))
	for n := range props {
		names = append(names, n)
	}
	sort.Strings(names)
	b.WriteString("| Field | Type | Required | Description |\n| --- | --- | --- | --- |\n")
	for _, n := range names {
		p := resolve(root, props[n].(node))
		r := "no"
		if req[n] {
			r = "yes"
		}
		desc, _ := p["description"].(string)
		desc = strings.ReplaceAll(strings.ReplaceAll(desc, "|", "/"), "\n", " ")
		fmt.Fprintf(b, "| `%s.%s` | %s | %s | %s |\n", prefix, n, typeOf(root, p), r, desc)
	}
}

func typeOf(root, p node) string {
	if e, ok := p["enum"].([]any); ok {
		parts := make([]string, 0, len(e))
		for _, v := range e {
			parts = append(parts, fmt.Sprintf("`%v`", v))
		}
		return strings.Join(parts, ", ")
	}
	if c, ok := p["const"]; ok {
		return fmt.Sprintf("`%v`", c)
	}
	t, _ := p["type"].(string)
	switch t {
	case "array":
		if it, ok := p["items"].(node); ok {
			return "list of " + typeOf(root, resolve(root, it))
		}
		return "list"
	case "":
		for _, key := range []string{"oneOf", "anyOf"} {
			if alts, ok := p[key].([]any); ok {
				parts := make([]string, 0, len(alts))
				for _, a := range alts {
					if m, ok := a.(node); ok {
						parts = append(parts, typeOf(root, resolve(root, m)))
					}
				}
				return strings.Join(parts, " or ")
			}
		}
		return "any"
	}
	return t
}
