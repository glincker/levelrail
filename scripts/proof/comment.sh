#!/usr/bin/env bash
# Usage: comment.sh <pr|issue> <number> [--dry-run]
# Builds ONE comment from the generated tables and creates or updates the
# existing comment carrying the marker. Images go to the proof-artifacts branch.
set -euo pipefail
# shellcheck source=lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

kind="${1:?usage: comment.sh <pr|issue> <number>}"
num="${2:?usage: comment.sh <pr|issue> <number>}"
dry=0
[ "${3:-}" = "--dry-run" ] && dry=1
MARKER='<!-- levelrail-proof -->'
BRANCH=proof-artifacts
KEEP="${LEVELRAIL_PROOF_KEEP_SETS:-5}"
sha="$(git -C "$PROOF_ROOT" rev-parse HEAD)"
sha7="${sha:0:7}"
[ -f "$PROOF_OUT/metrics.md" ] || "$PROOF_ROOT/scripts/proof/metrics.sh" >"$PROOF_OUT/metrics.md"
[ -f "$PROOF_OUT/capabilities.md" ] || "$PROOF_ROOT/scripts/proof/capabilities.sh" >"$PROOF_OUT/capabilities.md" || true

slug=""
if [ "$dry" = 0 ]; then
  slug="$(gh repo view --json nameWithOwner --jq .nameWithOwner)"
fi

shots_md=""
if [ -s "$PROOF_OUT/shots/shots.tsv" ]; then
  if [ "$dry" = 1 ]; then
    base_url="file://$PROOF_OUT/shots"
  else
    base_url="https://raw.githubusercontent.com/$slug/$BRANCH/pr-$num/$sha7"
    wt="$(mktemp -d "${TMPDIR:-/tmp}/levelrail-proof-wt.XXXXXX")"
    rm -rf "$wt"
    cleanup_wt() { git -C "$PROOF_ROOT" worktree remove --force "$wt" >/dev/null 2>&1 || true; git -C "$PROOF_ROOT" worktree prune; }
    trap cleanup_wt EXIT
    if git -C "$PROOF_ROOT" fetch -q origin "$BRANCH" 2>/dev/null; then
      git -C "$PROOF_ROOT" worktree add -q --detach "$wt" "origin/$BRANCH"
    else
      git -C "$PROOF_ROOT" worktree add -q --detach "$wt" HEAD
      git -C "$wt" checkout -q --orphan "$BRANCH"
      git -C "$wt" rm -rq -f . >/dev/null 2>&1 || true
    fi
    mkdir -p "$wt/pr-$num/$sha7"
    cp "$PROOF_OUT"/shots/*.webp "$wt/pr-$num/$sha7/"
    echo "$sha7" >>"$wt/pr-$num/ORDER"
    # Keep only the newest KEEP sets for this PR.
    mapfile -t order < <(awk '!s[$0]++' "$wt/pr-$num/ORDER")
    if [ "${#order[@]}" -gt "$KEEP" ]; then
      for old in "${order[@]:0:${#order[@]}-KEEP}"; do rm -rf "${wt:?}/pr-$num/$old"; done
      printf '%s\n' "${order[@]:${#order[@]}-KEEP}" >"$wt/pr-$num/ORDER"
    else
      printf '%s\n' "${order[@]}" >"$wt/pr-$num/ORDER"
    fi
    git -C "$wt" add -A
    git -C "$wt" commit -q -m "chore: proof images for $kind $num at $sha7" || true
    git -C "$wt" push -q origin "HEAD:refs/heads/$BRANCH"
  fi
  shots_md=$'### Screenshots\n\n'
  while IFS=$'\t' read -r file label note; do
    shots_md+="**$label** ($note)"$'\n\n'"![${label}](${base_url}/${file})"$'\n\n'
  done <"$PROOF_OUT/shots/shots.tsv"
fi

body="$PROOF_OUT/comment.md"
{
  echo "$MARKER"
  echo "## Proof for \`$sha7\`"
  echo
  echo "Generated by scripts/proof from commit \`$sha\`. Nothing below is hand written."
  echo
  echo "### Capabilities"
  echo
  cat "$PROOF_OUT/capabilities.md"
  echo
  echo "### Metrics"
  echo
  cat "$PROOF_OUT/metrics.md"
  echo
  if [ -s "$PROOF_OUT/transcripts.md" ] && ! grep -q '^no mapped transcripts' "$PROOF_OUT/transcripts.md"; then
    echo "### Transcripts"
    echo
    cat "$PROOF_OUT/transcripts.md"
    echo
  fi
  [ -n "$shots_md" ] && printf '%s\n' "$shots_md"
} >"$body"

if [ "$dry" = 1 ]; then
  cat "$body"
  exit 0
fi

existing="$(gh api "repos/$slug/issues/$num/comments" --paginate \
  --jq ".[] | select(.body | contains(\"$MARKER\")) | .id" | head -1)"
if [ -n "$existing" ]; then
  gh api -X PATCH "repos/$slug/issues/comments/$existing" -F "body=@$body" >/dev/null
  echo "comment.sh: updated comment $existing on $kind $num"
else
  gh api -X POST "repos/$slug/issues/$num/comments" -F "body=@$body" >/dev/null
  echo "comment.sh: created comment on $kind $num"
fi
