// Command gen-go-sdk writes sdk/go/levelrail/operations_gen.go from
// docs/public/openapi.json. Output is deterministic (sorted, no timestamps).
// With -check it writes nothing and exits 1 when the committed file is stale.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	specRel = "docs/public/openapi.json"
	outRel  = "sdk/go/levelrail/operations_gen.go"
)

var methods = []string{"get", "post", "put", "patch", "delete", "head"}

type spec struct {
	Paths map[string]map[string]json.RawMessage `json:"paths"`
}

type operation struct {
	OperationID string `json:"operationId"`
	RequestBody *struct {
		Content map[string]json.RawMessage `json:"content"`
	} `json:"requestBody"`
}

type row struct {
	id, method, path string
	body, stream     bool
}

// render turns the OpenAPI document into the Go source of the operation table.
func render(specJSON []byte) ([]byte, error) {
	var s spec
	if err := json.Unmarshal(specJSON, &s); err != nil {
		return nil, fmt.Errorf("parse spec: %w", err)
	}
	var rows []row
	seen := map[string]bool{}
	for path, item := range s.Paths {
		for _, m := range methods {
			raw, ok := item[m]
			if !ok {
				continue
			}
			var op operation
			if err := json.Unmarshal(raw, &op); err != nil {
				return nil, fmt.Errorf("parse %s %s: %w", m, path, err)
			}
			if op.OperationID == "" || seen[op.OperationID] {
				return nil, fmt.Errorf("missing or duplicate operationId %q (%s %s)", op.OperationID, m, path)
			}
			seen[op.OperationID] = true
			rows = append(rows, row{
				id: op.OperationID, method: strings.ToUpper(m), path: path,
				body:   op.RequestBody != nil,
				stream: strings.HasSuffix(op.OperationID, "Stream") || strings.HasSuffix(path, "/stream") || path == "/api/v1/events/changes",
			})
		}
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].id < rows[j].id })

	var b bytes.Buffer
	b.WriteString("// Code generated by scripts/gen-go-sdk from docs/public/openapi.json. DO NOT EDIT.\n\n")
	b.WriteString("package levelrail\n\n")
	b.WriteString("// Operations maps every OpenAPI operationId to its method and path template.\n")
	b.WriteString("var Operations = map[string]Operation{\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\t%q: {Method: %q, Path: %q, HasBody: %t, Stream: %t},\n", r.id, r.method, r.path, r.body, r.stream)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func main() {
	check := flag.Bool("check", false, "fail when the committed file is stale")
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	in, err := os.ReadFile(filepath.Join(*root, specRel)) //nolint:gosec // fixed repo-relative path
	if err != nil {
		fatal(err)
	}
	out, err := render(in)
	if err != nil {
		fatal(err)
	}
	target := filepath.Join(*root, outRel)
	if *check {
		cur, _ := os.ReadFile(target) //nolint:gosec // fixed repo-relative path
		if !bytes.Equal(cur, out) {
			fmt.Fprintf(os.Stderr, "%s is stale, run: go run ./scripts/gen-go-sdk\n", outRel)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(target, out, 0o644); err != nil { //nolint:gosec // generated source, world-readable by design
		fatal(err)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "gen-go-sdk:", err)
	os.Exit(1)
}
