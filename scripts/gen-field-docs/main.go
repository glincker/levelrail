// Command gen-field-docs writes docs/backup-target-fields.md from the field descriptor
// registry so the docs table cannot drift from the code.
//
// Usage (from the repo root): go run ./scripts/gen-field-docs
package main

import (
	"fmt"
	"os"

	"github.com/GLINCKER/levelrail/internal/fielddesc"
)

type page struct {
	resource, path, title, desc, slug, route string
}

var pages = []page{
	{fielddesc.BackupTarget, "docs/backup-target-fields.md", "Backup target fields", "Every field of a backup target with its type, requirement, visibility rule and CLI flag.", "backup-target-fields", "/api/v1/backup-targets/field-descriptors"},
	{fielddesc.LogDrain, "docs/log-drain-fields.md", "Log drain fields", "Every field of an app log drain with its type, requirement, visibility rule and CLI flag.", "log-drain-fields", "/api/v1/log-drains/field-descriptors"},
}

func header(p page) string {
	return "---\ntitle: \"" + p.title + "\"\ndescription: " + p.desc + "\n\"og:url\": \"https://docs.levelrail.com/" + p.slug + "\"\n---\n\n" +
		"{/* Generated by scripts/gen-field-docs from internal/fielddesc. Do not edit by hand. */}\n\n" +
		"The dashboard form, the CLI flags and the API all read one field registry, served at `GET " + p.route + "`. Secrets are write only: they are accepted on create and update and never returned.\n\n"
}

func main() {
	for _, p := range pages {
		r, ok := fielddesc.Get(p.resource)
		if !ok {
			fmt.Fprintln(os.Stderr, p.resource+" descriptors are not registered")
			os.Exit(1)
		}
		if err := os.WriteFile(p.path, []byte(header(p)+r.Markdown()), 0o644); err != nil { //nolint:gosec // docs file
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}
