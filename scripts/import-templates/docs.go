func cell(s string) string {
	if s == "" {
		return "-"
	}
	return strings.ReplaceAll(s, "|", "\\|")
}

func renderDocsPage(rep report) string {
	var b strings.Builder
	b.WriteString("---\n")
	b.WriteString("description: What the template import pipeline converted from the upstream catalog, why the rest was skipped, and the settings, ports and volumes of every imported template\n")
	b.WriteString("---\n\n# Imported templates\n\n")
	b.WriteString("This page is generated by `go run ./scripts/import-templates`. It lists the templates converted from the upstream service catalog (Apache-2.0, see the attribution in `internal/catalog/manifests/NOTICE`) and the reason every other upstream file was left out. The machine-readable version is `docs/template-import-report.json`.\n\n")
	fmt.Fprintf(&b, "Of %d upstream files, %d are committed as installable templates, %d convert cleanly but are not committed (they overlap an older hand-written entry or were left for a later batch), and %d were skipped.\n\n", rep.Total, rep.Committed, rep.Convertible, rep.Skipped)

	b.WriteString("## What the converter does\n\n")
	b.WriteString("- Address variables become the install form's domain prompts: the upstream URL form resolves to `https://<domain>` and the host form to the bare host.\n")
	b.WriteString("- Password, user, hex and base64 variables become generated settings with their lengths. A generated value used in a command or healthcheck is exposed to the shell as an environment variable.\n")
	b.WriteString("- Variables with a default are inlined; variables without one become settings you can fill in.\n")
	b.WriteString("- Relative bind mounts of directories become named volumes. Mounts of files or of repository content are refused.\n")
	b.WriteString("- A TCP-only healthcheck on a web service becomes an HTTP probe, and a web service with no healthcheck gets one.\n")
	b.WriteString("- Every manifest then goes through the same loader, compose validator and Docker guard rules a real install uses.\n\n")

	b.WriteString("## Skipped templates\n\n| Reason | Templates | Meaning |\n| --- | --- | --- |\n")
	for _, code := range sortedKeys(rep.SkipReasons) {
		fmt.Fprintf(&b, "| `%s` | %d | %s |\n", code, rep.SkipReasons[code], cell(reasonMeaning[code]))
	}

	byCategory := map[string][]reportEntry{}
	for _, e := range rep.Entries {
		if e.Status == statusCommitted && e.Summary != nil {
			byCategory[e.Summary.Category] = append(byCategory[e.Summary.Category], e)
		}
	}
	cats := make([]string, 0, len(byCategory))
	for c := range byCategory {
		cats = append(cats, c)
	}
	sort.Strings(cats)
	b.WriteString("\n## Imported templates\n")
	for _, c := range cats {
		fmt.Fprintf(&b, "\n### %s\n\n| Template | Services | Ports | Volumes | Generated | Settings |\n| --- | --- | --- | --- | --- | --- |\n", c)
		entries := byCategory[c]
		sort.Slice(entries, func(i, j int) bool { return entries[i].ID < entries[j].ID })
		for _, e := range entries {
			s := e.Summary
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s |\n", e.ID,
				cell(strings.Join(s.Services, ", ")), cell(strings.Join(s.Ports, ", ")),
				cell(strings.Join(s.Volumes, ", ")), cell(strings.Join(s.Generated, ", ")),
				cell(strings.Join(s.UserPrompt, ", ")))
		}
	}
	b.WriteString("\nInstall any of them with `levelrail-cli templates install <id>` or from the template's page in the dashboard. See [Compose apps](/compose-apps#templates).\n")
	return b.String()
}
