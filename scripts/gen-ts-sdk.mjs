#!/usr/bin/env node
// Generates sdk/typescript from docs/public/openapi.json. Output is deterministic
// (no timestamps, sorted keys). `--check` writes nothing and exits 1 when files are stale.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Single place for the package identity until the owner picks the npm scope.
export const PACKAGE_NAME = "levelrail-sdk-placeholder";
export const SDK_VERSION = "0.1.0";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = join(root, "docs/public/openapi.json");
const sdkDir = join(root, "sdk/typescript");
const METHODS = ["get", "post", "put", "patch", "delete", "head"];
const HEADER = "// Code generated by scripts/gen-ts-sdk.mjs from docs/public/openapi.json. DO NOT EDIT.\n";

const NAMESPACES = [
  ["builders", (p) => /^\/api\/v1\/environments\/\{id\}\/builders/.test(p)],
  ["environments", (p) => /^\/api\/v1\/environments(\/|$)/.test(p)],
  ["deploys", (p) => /^\/api\/v1\/apps\/\{name\}\/(deploys|deployments)(\/|$)/.test(p) || /^\/api\/v1\/(deployments|deploys|deploy-)/.test(p)],
  ["apps", (p) => /^\/api\/v1\/apps(\/|$)/.test(p)],
  ["staticSites", (p) => /^\/api\/v1\/static-sites(\/|$)/.test(p)],
  ["nodes", (p) => /^\/api\/v1\/nodes(\/|$)/.test(p)],
  ["tokens", (p) => /^\/api\/v1\/(auth\/)?tokens(\/|$)/.test(p)],
  ["domains", (p) => /^\/api\/v1\/domains(\/|$)/.test(p)],
];

// Keeps doc text single-line, ASCII-dash only and safe inside a block comment.
function clean(text) {
  return String(text ?? "")
    .replace(new RegExp(`[${String.fromCharCode(0x2013, 0x2014)}]`, "g"), "-")
    .replace(/\*\//g, "* /")
    .replace(/\s+/g, " ")
    .trim();
}

function firstSentence(text, max = 110) {
  const t = clean(text);
  const m = t.match(/^(.+?[.!?])(\s|$)/);
  const s = m ? m[1] : t;
  return s.length > max ? s.slice(0, max - 3).trimEnd() + "..." : s;
}

function resolveRef(spec, node) {
  if (node && node.$ref) {
    return node.$ref.split("/").slice(1).reduce((acc, k) => acc?.[k], spec);
  }
  return node;
}

// Returns "" when the schema says nothing useful, so the caller falls back to a generic type.
function tsType(spec, node, depth = 0) {
  if (!node || depth > 6) return "unknown";
  if (node.$ref) return `Schemas[${JSON.stringify(node.$ref.split("/").pop())}]`;
  if (node.enum) return node.enum.map((v) => JSON.stringify(v)).join(" | ");
  for (const key of ["oneOf", "anyOf"]) {
    if (node[key]) return node[key].map((n) => tsType(spec, n, depth + 1)).join(" | ");
  }
  if (node.allOf) return node.allOf.map((n) => tsType(spec, n, depth + 1)).join(" & ");
  const nullable = node.nullable ? " | null" : "";
  switch (node.type) {
    case "string": return "string" + nullable;
    case "integer":
    case "number": return "number" + nullable;
    case "boolean": return "boolean" + nullable;
    case "array": return `Array<${tsType(spec, node.items, depth + 1)}>` + nullable;
    case "object": {
      const props = Object.keys(node.properties ?? {}).sort();
      const req = new Set(node.required ?? []);
      const parts = props.map((k) => `${JSON.stringify(k)}${req.has(k) ? "" : "?"}: ${tsType(spec, node.properties[k], depth + 1)}`);
      if (node.additionalProperties === true || (node.additionalProperties && typeof node.additionalProperties === "object" && props.length === 0)) {
        const v = node.additionalProperties === true ? "unknown" : tsType(spec, node.additionalProperties, depth + 1);
        parts.push(`[key: string]: ${v}`);
      }
      return parts.length ? `{ ${parts.join("; ")} }` : "Record<string, unknown>";
    }
    default: return "unknown";
  }
}

// A schema is "informative" when it constrains more than an open object or nothing.
function informative(schema) {
  if (!schema || Object.keys(schema).length === 0) return false;
  if (schema.type === "object" && !schema.properties && !schema.required) return false;
  return true;
}

function collect(spec) {
  const ops = [];
  for (const path of Object.keys(spec.paths).sort()) {
    for (const m of METHODS) {
      const op = spec.paths[path][m];
      if (!op) continue;
      const id = op.operationId;
      const body = op.requestBody?.content?.["application/json"]?.schema;
      const ok = Object.entries(op.responses ?? {}).find(([c]) => /^2/.test(c));
      const respSchema = ok?.[1]?.content?.["application/json"]?.schema;
      ops.push({
        id,
        method: m.toUpperCase(),
        path,
        hasBody: Boolean(op.requestBody),
        sse: /Stream$/.test(id) || /\/stream$/.test(path),
        summary: clean(op.summary),
        ability: op["x-required-ability"] ?? "",
        bodyType: informative(body) ? tsType(spec, body) : "",
        respType: informative(respSchema) ? tsType(spec, respSchema) : "",
      });
    }
  }
  const seen = new Set();
  for (const o of ops) {
    if (!o.id || seen.has(o.id)) throw new Error(`missing or duplicate operationId: ${o.id} (${o.method} ${o.path})`);
    seen.add(o.id);
  }
  return ops;
}

function doc(o) {
  const ab = o.ability ? ` Requires \`${o.ability}\`.` : "";
  return `/** ${firstSentence(o.summary || o.id)}${ab} ${o.method} ${o.path} */`;
}

function genOperations(ops) {
  const lines = [HEADER, "export const operations = {"];
  for (const o of ops) {
    lines.push(`  ${o.id}: [${JSON.stringify(o.method)},${JSON.stringify(o.path)},${o.hasBody ? 1 : 0},${o.sse ? 1 : 0}],`);
  }
  lines.push("} as const;", "", "export type OperationId = keyof typeof operations;", "");
  return lines.join("\n");
}

function genTypes(spec, ops) {
  const out = [HEADER];
  const schemas = spec.components?.schemas ?? {};
  out.push("export interface Schemas {");
  for (const k of Object.keys(schemas).sort()) out.push(`  ${JSON.stringify(k)}: ${tsType({ components: { schemas } }, schemas[k])};`);
  out.push("}", "");
  const typed = ops.filter((o) => o.bodyType || o.respType);
  if (typed.length === 0) {
    out.push("export type OperationTypes = Record<never, never>;", "");
  } else {
    out.push("export interface OperationTypes {");
    for (const o of typed) {
      const parts = [];
      if (o.bodyType) parts.push(`body: ${o.bodyType}`);
      if (o.respType) parts.push(`response: ${o.respType}`);
      out.push(`  ${o.id}: { ${parts.join("; ")} };`);
    }
    out.push("}", "");
  }
  return out.join("\n");
}

function methodNames(ops) {
  const lower = (s) => s.charAt(0).toLowerCase() + s.slice(1);
  const byNs = new Map(NAMESPACES.map(([n]) => [n, []]));
  for (const o of ops) {
    const ns = NAMESPACES.find(([, test]) => test(o.path));
    if (ns) byNs.get(ns[0]).push(o);
  }
  const result = [];
  for (const [ns, list] of byNs) {
    const short = list.map((o) => lower(o.id.replace(/^handle/, "")));
    const counts = new Map();
    short.forEach((n) => counts.set(n, (counts.get(n) ?? 0) + 1));
    const entries = list.map((o, i) => [counts.get(short[i]) > 1 ? lower(o.id) : short[i], o]);
    result.push([ns, entries]);
  }
  return result;
}

function genResources(ops) {
  const out = [HEADER, 'import type { OperationFn } from "../types.ts";', "", "type Bind = <K extends keyof typeof import(\"./operations.ts\").operations>(id: K) => OperationFn<K>;", ""];
  out.push("export function createResources(op: Bind) {", "  return {");
  for (const [ns, entries] of methodNames(ops)) {
    out.push(`    ${ns}: {`);
    for (const [name, o] of entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))) {
      out.push(`      ${doc(o)}`, `      ${name}: op(${JSON.stringify(o.id)}),`);
    }
    out.push("    },");
  }
  out.push("  };", "}", "", "export type Resources = ReturnType<typeof createResources>;", "");
  return out.join("\n");
}

function packageJson() {
  const pkg = {
    name: PACKAGE_NAME,
    version: SDK_VERSION,
    description: "Typed TypeScript client for the Levelrail control plane API. Zero runtime dependencies.",
    private: true,
    type: "module",
    license: "Apache-2.0",
    engines: { node: ">=20" },
    sideEffects: false,
    main: "./dist/index.js",
    types: "./dist/index.d.ts",
    exports: { ".": { types: "./dist/index.d.ts", default: "./dist/index.js" } },
    files: ["dist", "README.md"],
    scripts: {
      build: "tsc -p tsconfig.json",
      generate: "node ../../scripts/gen-ts-sdk.mjs",
      test: "node --test test/*.test.ts test/*.test.mjs",
    },
    devDependencies: { typescript: "^5.9.0" },
  };
  return JSON.stringify(pkg, null, 2) + "\n";
}

function readme() {
  const tpl = readFileSync(join(sdkDir, "README.tpl.md"), "utf8");
  return tpl.replaceAll("{{PACKAGE}}", PACKAGE_NAME);
}

export function buildFiles() {
  const spec = JSON.parse(readFileSync(specPath, "utf8"));
  const ops = collect(spec);
  return {
    "package.json": packageJson(),
    "README.md": readme(),
    "src/generated/operations.ts": genOperations(ops),
    "src/generated/types.ts": genTypes(spec, ops),
    "src/generated/resources.ts": genResources(ops),
  };
}

function main() {
  const check = process.argv.includes("--check");
  const files = buildFiles();
  const stale = [];
  for (const [rel, content] of Object.entries(files)) {
    const file = join(sdkDir, rel);
    const current = existsSync(file) ? readFileSync(file, "utf8") : null;
    if (current === content) continue;
    stale.push(rel);
    if (!check) {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, content);
    }
  }
  if (check && stale.length) {
    process.stderr.write(`sdk/typescript is stale: ${stale.join(", ")}\nrun: node scripts/gen-ts-sdk.mjs\n`);
    process.exit(1);
  }
  process.stdout.write(check ? "sdk/typescript is up to date\n" : `wrote ${stale.length} file(s)\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
