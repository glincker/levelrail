// Command gen-arm-compat writes docs/arm-compatibility.md from the catalog's
// registry scan (platforms.json) and the recorded smoke results in
// docs/templates-status.md. Pass -check to fail instead of writing when stale.
package main

import (
	"flag"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"

	"github.com/GLINCKER/levelrail/internal/catalog"
)

const (
	pagePath   = "docs/arm-compatibility.md"
	statusPath = "docs/templates-status.md"
)

var smokeRow = regexp.MustCompile("^\\| `([^`]+)` \\| ([a-z_]+) \\| \\d+ \\|")

// smokeResults reads the first table of the status page: id to recorded result.
func smokeResults(status string) map[string]string {
	out := map[string]string{}
	in := false
	for _, line := range strings.Split(status, "\n") {
		if strings.HasPrefix(line, "| Template | Result |") {
			in = true
			continue
		}
		if !in {
			continue
		}
		if !strings.HasPrefix(line, "|") {
			break
		}
		if m := smokeRow.FindStringSubmatch(line); m != nil {
			out[m[1]] = m[2]
		}
	}
	return out
}

func scanStatus(t catalog.Template) string {
	if len(t.Platforms) == 0 {
		return "unknown"
	}
	for _, p := range t.Platforms {
		if p == "linux/arm64" {
			return "listed"
		}
	}
	return "amd64 only"
}

func page(templates []catalog.Template, scannedAt string, smoke map[string]string) string {
	ts := append([]catalog.Template(nil), templates...)
	sort.Slice(ts, func(i, j int) bool { return ts[i].ID < ts[j].ID })
	counts := map[string]int{}
	var rows strings.Builder
	for _, t := range ts {
		s := scanStatus(t)
		counts[s]++
		run := "not tested"
		if r, ok := smoke[t.ID]; ok {
			run = r
		}
		fmt.Fprintf(&rows, "| `%s` | %s | %s |\n", t.ID, s, run)
	}
	if scannedAt == "" {
		scannedAt = "never"
	}
	var b strings.Builder
	b.WriteString("---\ntitle: \"Arm64 compatibility\"\n")
	b.WriteString("description: \"Which one-click templates list a linux/arm64 image, for Raspberry Pi and Arm VMs, generated from the registry scan.\"\n")
	b.WriteString("\"og:url\": \"https://docs.levelrail.com/arm-compatibility\"\n---\n\n")
	b.WriteString("{/* Generated by scripts/gen-arm-compat from internal/catalog/platforms.json and docs/templates-status.md. Do not edit by hand. */}\n\n")
	fmt.Fprintf(&b, "Registry scan date: %s. This page is generated, so it only says what the scan and the recorded smoke runs say.\n\n", scannedAt)
	b.WriteString("- **listed**: every image the template uses lists `linux/arm64` in its registry manifest. That is a manifest fact, not proof the app runs well on Arm.\n")
	b.WriteString("- **amd64 only**: at least one image lists no `linux/arm64`, so the template has no native Arm image.\n")
	b.WriteString("- **unknown**: the scan could not read a manifest, or the image tag is chosen at install time. This is not a claim either way.\n\n")
	b.WriteString("The smoke column is the result recorded on the Arm test host in [Template status](/templates-status). `not tested` means no recorded run, not a failure.\n\n")
	fmt.Fprintf(&b, "**%d listed, %d amd64 only, %d unknown** of %d templates.\n\n", counts["listed"], counts["amd64 only"], counts["unknown"], len(ts))
	b.WriteString("| Template | arm64 in manifest | Smoke run on Arm host |\n| --- | --- | --- |\n")
	b.WriteString(rows.String())
	return b.String()
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}

func main() {
	check := flag.Bool("check", false, "fail if the page is stale")
	flag.Parse()
	status, err := os.ReadFile(statusPath)
	if err != nil {
		fail(err)
	}
	out := page(catalog.Templates, catalog.PlatformsData().ScannedAt, smokeResults(string(status)))
	old, _ := os.ReadFile(pagePath)
	if string(old) == out {
		return
	}
	if *check {
		fail(fmt.Errorf("%s is stale; run go run ./scripts/gen-arm-compat", pagePath))
	}
	if err := os.WriteFile(pagePath, []byte(out), 0o600); err != nil { //nolint:gosec // fixed repo doc path
		fail(err)
	}
}
