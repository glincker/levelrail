void i18n
  .use(lazyBackend)
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    fallbackLng: 'en',
    supportedLngs: SUPPORTED_LANGUAGES,
    detection: { convertDetectedLanguage: normalizeDetectedLanguage },
    nonExplicitSupportedLngs: true,
    ns: ['common'],
    defaultNS: 'common',
    interpolation: {
      // React already escapes rendered output.
      escapeValue: false,
    },
    react: {
      useSuspense: true,
    },
  })

// Mirror the active language into the dependency-free holder shared code reads.
i18n.on('initialized', () => setActiveLocale(i18n.language))
i18n.on('languageChanged', setActiveLocale)
setActiveLocale(i18n.language)
if (typeof document !== 'undefined') syncDocumentLanguage(i18n)
