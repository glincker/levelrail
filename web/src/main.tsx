import { StrictMode, Suspense } from 'react'
import { createRoot } from 'react-dom/client'
import {
  MutationCache,
  QueryCache,
  QueryClient,
  QueryClientProvider,
} from '@tanstack/react-query'
import { RouterProvider, createRouter } from '@tanstack/react-router'
import './index.css'
import './lib/density'
import './lib/pageWidth'
import { isUnauthorized } from './lib/apiError'
import { clearStoredUsername, getStoredUsername } from './lib/authStore'
import {
  attachConnectionClient,
  reportError,
  reportSuccess,
} from './lib/connectionStore'
import { safeReturnPath } from './lib/connectionState'
import { RouteErrorFallback } from './components/RouteErrorFallback'
import { PageSpinner } from './components/ui/page-spinner'
import { RootFallback } from './components/ui/shell-skeleton'
import { prefetchNamespaces, scheduleIdle } from './i18n/prefetch'
import { routeViewTransition } from './lib/routeTransition'

// routeTree.gen.ts is generated by @tanstack/router-plugin (see
// vite.config.ts) from the files under src/routes. It does not exist
// until `npm run dev` or `npm run build` has run at least once; it is
// gitignored, not hand-written.
import { routeTree } from './routeTree.gen'

// Filled in right after createRouter below with a plain closure, not a
// stored reference to the router itself: TanStack Router's type-level
// Register['router'] augmentation (the `declare module` block below)
// needs `typeof router` on the `const router = createRouter(...)`
// assignment to stay exactly as inferred, un-widened by ever flowing
// through a separately-typed variable first (that produced a real tsc
// error, a self-referential mismatch between the router's type before
// and after the Register augmentation resolves). A plain function
// reference sidesteps the whole issue.
let navigateToLogin: ((signedOut: boolean) => void) | null = null

// Global 401 handling: every fetcher under src/queries/*.ts now throws an
// ApiError with a real status code (lib/apiError.ts) instead of a plain
// Error, so a 401 arriving from any query or mutation, anywhere in the
// app, is detected here in exactly one place and redirected to /login,
// distinct from how a 404/500 still renders in each route's own error
// boundary (AppDetailError and friends keep working exactly as before,
// since onError here only acts on 401).
function handleQueryError(error: unknown): void {
  reportError(error)
  if (isUnauthorized(error)) {
    // A 401 while we believed we were signed in means the session ended server side (expiry, restart, upgrade).
    const hadSession = getStoredUsername() !== null
    clearStoredUsername()
    navigateToLogin?.(hadSession)
  }
}

const queryClient = new QueryClient({
  queryCache: new QueryCache({
    onError: handleQueryError,
    onSuccess: reportSuccess,
  }),
  mutationCache: new MutationCache({ onError: handleQueryError }),
  // staleTime dedupes mounts of the same key; polling hooks keep their own intervals (paused when hidden).
  defaultOptions: { queries: { staleTime: 10_000, gcTime: 5 * 60_000 } },
})
attachConnectionClient(queryClient)

// Router context carries the QueryClient (see routes/__root.tsx) so every
// route loader can prime the Query cache without a module-level import
// cycle back into this file.
// defaultErrorComponent/defaultPendingComponent are the fallback for the
// majority of routes that define no errorComponent/pendingComponent of
// their own; routes with route-specific needs (e.g. apps/$name.tsx's
// AppDetailError) still override these per-route.
const router = createRouter({
  routeTree,
  context: { queryClient },
  defaultPreload: 'intent',
  defaultErrorComponent: RouteErrorFallback,
  defaultPendingComponent: PageSpinner,
  defaultViewTransition: routeViewTransition(),
  // Stock timings (1000ms before the skeleton, 500ms minimum once shown) make a slow tab feel frozen, then flash.
  defaultPendingMs: Number(import.meta.env.VITE_ROUTE_PENDING_MS ?? 250),
  defaultPendingMinMs: Number(import.meta.env.VITE_ROUTE_PENDING_MIN_MS ?? 300),
})
navigateToLogin = (signedOut) => {
  // A failed login/register submission is itself a 401/... mutation that
  // flows through this same shared mutationCache, so this can fire while
  // already sitting on /login (LoginForm renders its own error message
  // from that same rejection). Guarded here rather than skipped entirely,
  // since a real mid-session 401 on any other route still needs this.
  if (router.state.location.pathname === '/login') {
    return
  }
  const here = safeReturnPath(
    router.state.location.pathname + router.state.location.searchStr,
  )
  void router.navigate({
    to: '/login',
    search: {
      ...(here && here !== '/' ? { redirect: here } : {}),
      ...(signedOut ? { signed_out: 'session' } : {}),
    },
  })
}

declare module '@tanstack/react-router' {
  interface Register {
    router: typeof router
  }
}

const rootElement = document.getElementById('root')
if (!rootElement) {
  throw new Error('root element not found')
}

// Dynamic import keeps i18next out of the main entry chunk's bundle-size budget.
void import('./i18n').then(({ default: i18n, NAMESPACES }) => {
  createRoot(rootElement).render(
    <StrictMode>
      {/* The common namespace (defaultNS) loads via lazyBackend on this
          first render; every other namespace suspends the same way the
          first time a route under it calls useTranslation. */}
      <Suspense fallback={<RootFallback />}>
        <QueryClientProvider client={queryClient}>
          <RouterProvider router={router} />
        </QueryClientProvider>
      </Suspense>
    </StrictMode>,
  )
  // Warm the remaining catalogues while idle so opening a tab never suspends on a fetch.
  if (import.meta.env.VITE_I18N_PREFETCH !== 'off') {
    prefetchNamespaces({
      namespaces: NAMESPACES,
      isLoaded: (ns) => i18n.hasLoadedNamespace(ns),
      load: (batch) => i18n.loadNamespaces(batch),
      schedule: scheduleIdle,
      batchSize: Number(import.meta.env.VITE_I18N_PREFETCH_BATCH ?? 4),
    })
  }
})
