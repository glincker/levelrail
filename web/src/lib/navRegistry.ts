const BY_ID = new Map(NAV_REGISTRY.map((e) => [e.id, e] as const))

export function registryEntry(id: string): NavRegistryEntry | undefined {
  return BY_ID.get(id)
}

// Palette-only pages read their path here so the route lives in one place.
export function registryPath(id: string): FileRouteTypes['to'] {
  const found = BY_ID.get(id)
  if (!found) throw new Error(`nav registry has no entry "${id}"`)
  return found.path
}
