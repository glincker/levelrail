// Derives the template id -> thesvg mark loaders from the catalog and the
// installed @thesvg/react, so a version bump alone picks up new icons.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import * as prettier from 'prettier'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const catalogDir = path.resolve(root, '../internal/catalog')
const distDir = path.join(root, 'node_modules/@thesvg/react/dist')
const slugsFile = path.join(root, 'src/lib/templateLogoSlugs.json')
const brandFile = path.join(root, 'src/lib/brandLogoSlugs.json')
const outFile = path.join(root, 'src/lib/templateLogos.generated.ts')

function catalogIds() {
  const ids = new Set()
  for (const file of readdirSync(catalogDir)) {
    if (!file.endsWith('.go') || file.endsWith('_test.go')) continue
    const src = readFileSync(path.join(catalogDir, file), 'utf8')
    for (const m of src.matchAll(/^\s+ID:\s+"([a-z0-9-]+)"/gm)) ids.add(m[1])
  }
  for (const dir of readdirSync(path.join(catalogDir, 'manifests'))) {
    ids.add(dir)
  }
  const contribDir = path.join(catalogDir, 'contrib')
  for (const file of readdirSync(contribDir)) {
    const src = readFileSync(path.join(contribDir, file), 'utf8')
    const m = /^id:\s*"?([a-z0-9-]+)"?/m.exec(src)
    if (m) ids.add(m[1])
  }
  return [...ids].sort()
}

// Without node_modules or the catalog (Docker web stage) the committed file wins.
if (!existsSync(distDir) || !existsSync(catalogDir)) process.exit(0)

const brandSlugs = JSON.parse(readFileSync(brandFile, 'utf8'))
const overrides = {
  ...JSON.parse(readFileSync(slugsFile, 'utf8')),
  ...brandSlugs,
}
const mapped = []
const missing = []
// Brand ids (frameworks, images, backup targets) are not catalog templates.
for (const id of [
  ...new Set([...catalogIds(), ...Object.keys(brandSlugs)]),
].sort()) {
  const entry = overrides[id] ?? id
  // An object entry pins a thesvg variant: { "slug": "go", "variant": "mono" }.
  const slug = typeof entry === 'string' ? entry : entry.slug
  const variant = typeof entry === 'string' ? undefined : entry.variant
  if (existsSync(path.join(distDir, `${slug}.js`))) mapped.push([id, slug, variant])
  else missing.push(id)
}

const key = (id) => (/^[a-z_$][a-z0-9_$]*$/i.test(id) ? id : `'${id}'`)
const src = `// Generated by scripts/gen-template-logos.mjs. Do not edit.
import { createElement, type ComponentType, type SVGProps } from 'react'

export type LogoComponent = ComponentType<SVGProps<SVGSVGElement>>
type VariantLogo = ComponentType<
  SVGProps<SVGSVGElement> & { variant?: 'light' | 'dark' | 'mono' }
>

export const TEMPLATE_LOGO_LOADERS: Record<
  string,
  () => Promise<{ default: LogoComponent }>
> = {
${mapped.map(([id, s, v]) => (v ? `  ${key(id)}: () => import('@thesvg/react/${s}').then((m) => ({ default: (props: SVGProps<SVGSVGElement>) => createElement(m.default as VariantLogo, { ...props, variant: '${v}' }) })),` : `  ${key(id)}: () => import('@thesvg/react/${s}'),`)).join('\n')}
}

export const MISSING_TEMPLATE_LOGOS: readonly string[] = [
${missing.map((id) => `  '${id}',`).join('\n')}
]
`
const cfg = (await prettier.resolveConfig(outFile)) ?? {}
const out = await prettier.format(src, { ...cfg, filepath: outFile })
if (!existsSync(outFile) || readFileSync(outFile, 'utf8') !== out) {
  writeFileSync(outFile, out)
}
process.stderr.write(
  `template logos: ${mapped.length} mapped, ${missing.length} missing\n`,
)
