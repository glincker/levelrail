#!/usr/bin/env node
// Generates src/generated/docsManifest.json from /docs: titles, headings,
// and README.md's own index parsed into sidebar categories. Committed,
// not gitignored, so no build ever depends on running this first (CI's
// own "generate routeTree.gen.ts" step calls `vite build` directly, not
// `npm run build`, so an npm pre-script hook would silently miss it).
// Re-run this manually after adding, removing, or retitling a doc under
// /docs or restructuring docs/README.md's index.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import path from 'node:path'

const docsDir = path.resolve(import.meta.dirname, '../../docs')
const outFile = path.resolve(
  import.meta.dirname,
  '../src/generated/docsManifest.ts',
)
const pathIndexFile = path.resolve(
  import.meta.dirname,
  '../src/generated/docsPathIndex.ts',
)

// Must match web/src/lib/slugify.ts exactly.
function slugify(text) {
  return text
    .toLowerCase()
    .trim()
    .replace(/[`~!@#$%^&*()+={}[\]|\\:;"'<>,.?/]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
}

function uniqueSlug(text, seen) {
  const base = slugify(text)
  const count = seen.get(base) ?? 0
  seen.set(base, count + 1)
  return count === 0 ? base : `${base}-${count}`
}

// Must match web/src/lib/docsPaths.ts exactly.
function filePathToRoutePath(relFile) {
  if (relFile === 'README.md') return '/'
  return `/${relFile.replace(/\.md$/, '')}`
}

function listMarkdownFiles(dir, base = '') {
  const out = []
  for (const entry of readdirSync(dir)) {
    if (entry.startsWith('.')) continue
    const full = path.join(dir, entry)
    const rel = base ? `${base}/${entry}` : entry
    if (statSync(full).isDirectory()) {
      out.push(...listMarkdownFiles(full, rel))
    } else if (entry.endsWith('.md')) {
      out.push(rel)
    }
  }
  return out
}

function stripFrontmatter(text) {
  if (!text.startsWith('---\n') && !text.startsWith('---\r\n')) return text
  const end = text.indexOf('\n---', 4)
  if (end === -1) return text
  const rest = text.slice(end + 4)
  return rest.startsWith('\n') ? rest.slice(1) : rest
}

function extractPage(relFile) {
  const raw = readFileSync(path.join(docsDir, relFile), 'utf8')
  const body = stripFrontmatter(raw)
  const lines = body.split('\n')
  let title
  const headings = []
  const seen = new Map()
  for (const line of lines) {
    const h1 = /^#\s+(.+)$/.exec(line)
    if (h1 && !title) {
      title = h1[1].trim()
      continue
    }
    const h = /^(#{2,3})\s+(.+)$/.exec(line)
    if (h) {
      const level = h[1].length
      const text = h[2].trim()
      headings.push({ id: uniqueSlug(text, seen), text, level })
    }
  }
  return {
    file: relFile,
    title: title ?? relFile,
    headings,
  }
}

function extractCategories(readmeText, pagesByPath) {
  const body = stripFrontmatter(readmeText)
  const lines = body.split('\n')
  const categories = []
  let current = null
  for (const line of lines) {
    const heading = /^###\s+(.+)$/.exec(line)
    if (heading) {
      current = { name: heading[1].trim(), docs: [] }
      categories.push(current)
      continue
    }
    if (!current) continue
    const link = /\[([^\]]+)\]\(([^)]+?)\)/.exec(line)
    if (!link) continue
    const [, , target] = link
    if (!target.endsWith('.md')) continue
    const relFile = path.posix.normalize(target)
    const routePath = filePathToRoutePath(relFile)
    const page = pagesByPath.get(routePath)
    if (!page) continue
    // README.md's own link text is the bare filename (a GitHub-preview
    // convention), not a human title; the sidebar wants the page's real
    // title (its own H1), not "getting-started.md".
    current.docs.push({ path: routePath, title: page.title })
  }
  return categories
}

const files = listMarkdownFiles(docsDir).filter((f) => f !== 'index.md')

const pages = {}
for (const relFile of files) {
  const routePath = filePathToRoutePath(relFile)
  pages[routePath] = extractPage(relFile)
}

const pagesByPath = new Map(Object.entries(pages))
const readmeText = readFileSync(path.join(docsDir, 'README.md'), 'utf8')
const categories = extractCategories(readmeText, pagesByPath)

const manifest = { categories, pages }
const banner =
  '// Generated by scripts/build-docs-manifest.mjs from /docs. Do not hand-edit; re-run the script instead.\n' +
  "import type { DocsManifest } from '../types/docs'\n\n" +
  `const docsManifest: DocsManifest = ${JSON.stringify(manifest, null, 2)}\n\n` +
  'export default docsManifest\n'
writeFileSync(outFile, banner)

// A tiny sibling of the full manifest, just the known path set: HelpLink
// and AppSidebar need only "does this path exist" and are eagerly loaded
// on every page, so they import this instead of the full manifest (all
// 32 pages' headings), which stays behind /help's own lazy chunk.
const pathIndexBanner =
  '// Generated by scripts/build-docs-manifest.mjs from /docs. Do not hand-edit; re-run the script instead.\n' +
  `const docsPathIndex: ReadonlySet<string> = new Set(${JSON.stringify(Object.keys(pages))})\n\n` +
  'export default docsPathIndex\n'
writeFileSync(pathIndexFile, pathIndexBanner)

// JSON.stringify's output doesn't match this repo's prettier config
// (single quotes, no semicolons); format in place so the generated
// files pass the pre-commit hook's prettier check without a manual step.
execFileSync(
  process.platform === 'win32' ? 'npx.cmd' : 'npx',
  ['--no', '--', 'prettier', '--write', outFile, pathIndexFile],
  { cwd: path.resolve(import.meta.dirname, '..'), stdio: 'inherit' },
)

console.log(
  `[build-docs-manifest] wrote ${Object.keys(pages).length} pages, ${categories.length} categories to ${path.relative(process.cwd(), outFile)} (+ docsPathIndex.ts)`,
)
